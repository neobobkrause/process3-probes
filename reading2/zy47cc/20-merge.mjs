  const readRules = () => {
    if (rules === undefined) rules = io.requiredChecks(slug, base);
    if (!rules) fail(`could not read the checks ${base} requires`);
    return rules;
  };
  // process3 itself: a base with no pin and no config in its history, not a first close into main.
